/**
 * gen-api-inventory — scan apps/server/src/routes and emit a complete, accurate
 * inventory of the HTTP API (method + path + domain + best-effort generic types)
 * for the in-app developer docs (/developers → API Reference). Re-run after
 * adding/changing routes so the docs never drift from the code:
 *
 *   node scripts/gen-api-inventory.mjs
 *
 * Output: apps/web/src/features/developers/apiInventory.generated.ts
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const ROUTES_DIR = path.join(ROOT, "apps/server/src/routes");
const OUT = path.join(ROOT, "apps/web/src/features/developers/apiInventory.generated.ts");

const METHODS = ["get", "post", "put", "patch", "delete"];

/** Read the balanced `<...>` (or `{...}`) block starting at `open` (the bracket
 *  index). Returns [innerText, indexAfterClose] or null. */
function readBalanced(src, open, openCh, closeCh) {
  let depth = 0;
  for (let i = open; i < src.length; i++) {
    const c = src[i];
    if (c === openCh) depth++;
    else if (c === closeCh) {
      depth--;
      if (depth === 0) return [src.slice(open + 1, i), i + 1];
    }
  }
  return null;
}

/** Pull `Key: {...}` (balanced) out of a TS generic body. */
function extractTypeField(generic, key) {
  const m = generic.match(new RegExp(`${key}\\s*:\\s*`));
  if (!m) return undefined;
  const at = m.index + m[0].length;
  if (generic[at] === "{") {
    const b = readBalanced(generic, at, "{", "}");
    if (b) return `{${b[0].trim()}}`.replace(/\s+/g, " ");
  }
  // non-object type (rare) → take up to the next ; or end
  const rest = generic.slice(at).split(/[;}]/)[0];
  return rest.trim() || undefined;
}

function parseFile(file) {
  const domain = path.basename(file, ".ts");
  const src = fs.readFileSync(file, "utf-8");
  const out = [];
  const re = new RegExp(`\\bapp\\.(${METHODS.join("|")})\\b`, "g");
  let m;
  while ((m = re.exec(src))) {
    const method = m[1].toUpperCase();
    let i = m.index + m[0].length;
    // optional generic <...>
    let generic = "";
    while (i < src.length && /\s/.test(src[i])) i++;
    if (src[i] === "<") {
      const b = readBalanced(src, i, "<", ">");
      if (b) {
        generic = b[0];
        i = b[1];
      }
    }
    // skip to "(" then to the first string literal = the path
    while (i < src.length && src[i] !== "(") i++;
    const pathMatch = src.slice(i, i + 400).match(/["'`]([^"'`]+)["'`]/);
    if (!pathMatch) continue;
    const rawPath = pathMatch[1];
    if (!rawPath.startsWith("/")) continue;
    const fullPath = domain === "health" ? rawPath : `/api${rawPath}`;
    out.push({
      method,
      path: fullPath,
      domain,
      params: generic ? extractTypeField(generic, "Params") : undefined,
      query: generic ? extractTypeField(generic, "Querystring") : undefined,
      body: generic ? extractTypeField(generic, "Body") : undefined,
    });
  }
  return out;
}

/** Domain → description, from the route registry (the server's single source of
 *  truth). Adding a CORE_ROUTES entry therefore documents its domain here too. */
function parseRegistryDescriptions() {
  const reg = path.join(ROUTES_DIR, "registry.ts");
  const out = {};
  if (!fs.existsSync(reg)) return out;
  const src = fs.readFileSync(reg, "utf-8");
  const re = /domain:\s*"([^"]+)",\s*description:\s*"([^"]+)"/g;
  let m;
  while ((m = re.exec(src))) out[m[1]] = m[2];
  return out;
}

const all = [];
for (const f of fs.readdirSync(ROUTES_DIR)) {
  if (!f.endsWith(".ts") || f === "registry.ts") continue;
  all.push(...parseFile(path.join(ROUTES_DIR, f)));
}
const descriptions = parseRegistryDescriptions();
// stable sort: domain, then path, then method
all.sort(
  (a, b) =>
    a.domain.localeCompare(b.domain) ||
    a.path.localeCompare(b.path) ||
    a.method.localeCompare(b.method),
);

const header = `/**
 * AUTO-GENERATED by scripts/gen-api-inventory.mjs — DO NOT EDIT BY HAND.
 * The complete HTTP API surface scanned from apps/server/src/routes.
 * Re-run \`node scripts/gen-api-inventory.mjs\` after changing routes.
 */
export interface ApiEndpoint {
  method: "GET" | "POST" | "PUT" | "PATCH" | "DELETE";
  path: string;
  domain: string;
  params?: string;
  query?: string;
  body?: string;
}

export const API_ENDPOINTS: ApiEndpoint[] = ${JSON.stringify(all, null, 2)};

/** Domain → description, sourced from the route registry (routes/registry.ts). */
export const DOMAIN_DESCRIPTIONS: Record<string, string> = ${JSON.stringify(descriptions, null, 2)};
`;

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, header, "utf-8");
console.log(`Wrote ${all.length} endpoints across ${new Set(all.map((e) => e.domain)).size} domains → ${path.relative(ROOT, OUT)}`);
